}

// Select Option (Radio button style)
function selectOption(option) {
    // Remove active from all
    document.querySelectorAll('.choice-btn').forEach(btn => {
        btn.classList.remove('active');
    });
    
    document.querySelectorAll('.form-content, .code-message').forEach(content => {
        content.classList.remove('active');
    });
    
    // Add active to selected
    if (option === 'noCode') {
        document.getElementById('noCodeOption').classList.add('active');
        document.getElementById('noCodeForm').classList.add('active');
    } else {
        document.getElementById('hasCodeOption').classList.add('active');
        document.getElementById('hasCodeMessage').classList.add('active');
        
