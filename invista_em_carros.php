document.addEventListener('DOMContentLoaded', function() {
    // Cria instância do sistema de vagas
    sistemaVagas = new SistemaVagas();
    
    // Scroll Animation Observer
    const observerOptions = {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    };
    
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible');
            }
        });
    }, observerOptions);
    
    // Observe all animation elements
    const animatedElements = document.querySelectorAll('.fade-in-up, .fade-in-left, .fade-in-right, .scale-in');
    animatedElements.forEach(element => {
        observer.observe(element);
    });
    
    // FAQ Toggle
    document.querySelectorAll('.faq-item').forEach(item => {
        item.querySelector('.faq-question').addEventListener('click', () => {
            item.classList.toggle('active');
        });
    });
    
    // Form Submit
    const leadForm = document.getElementById('leadForm');
    if (leadForm) {
        leadForm.addEventListener('submit', function(e) {
            e.preventDefault();
            
            const submitButton = this.querySelector('.submit-button');
            const originalText = submitButton.textContent;
            submitButton.disabled = true;
            submitButton.textContent = 'Enviando...';
            
            // Dados do formulário
            const formData = {
                nome: this.nome.value.trim(),
                email: this.email.value.trim(),
                whatsapp: this.whatsapp.value.trim(),
                source: 'landing_page'
            };
           
            fetch('/api/send-lead.php', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                },
                body: JSON.stringify(formData)
            })
            .then(response => response.json())
            .then(data => {
                if (data.success) {
                    // Diminui uma vaga quando o envio for bem-sucedido
                    sistemaVagas.diminuirVaga();
                    
                    // Mostra mensagem de sucesso
                    alert('✅ ' + (data.message || 'Código VIP solicitado com sucesso!'));
                    this.reset();
                    
                    // Analytics
                    if (typeof gtag !== 'undefined') {
                        gtag('event', 'generate_lead', {
                            'event_category': 'engagement',
                            'event_label': 'formulario_motorgo',
                            'value': 15000,
                            'currency': 'BRL',
                            'lead_source': 'landing_page'
                        });
                        
                        gtag('event', 'conversion', {
                            'send_to': 'G-SCCKRSE34V/conversion',
                            'value': 15000,
                            'currency': 'BRL'
                        });
                    }
                    
                    if (typeof fbq !== 'undefined') {
                        fbq('track', 'CompleteRegistration', {
                            value: 15000,
                            currency: 'BRL',
                            content_name: 'Código VIP MotorGo',
                            content_category: 'Investimento Automotivo'
                        });
                        
                        fbq('track', 'CompleteRegistration', {
                            value: 15000,
                            currency: 'BRL',
                            content_name: 'MotorGo Landing'
                        });
                    }
                } else {
                    throw new Error(data.error || 'Erro ao enviar');
                }
            })
            .catch(error => {
                console.error('Erro:', error);
                alert('❌ Erro ao enviar. Por favor, tente novamente.');
            })
            .finally(() => {
                submitButton.disabled = false;
                submitButton.textContent = originalText;
            });
        });
    }
    
    // Track de cliques importantes
    document.querySelectorAll('.cta-button').forEach(button => {
        button.addEventListener('click', function() {
            if (typeof gtag !== 'undefined') {
                gtag('event', 'click', {
                    'event_category': 'CTA',
                    'event_label': this.textContent.trim()
                });
            }
        });
    });
    
    // Track visualização de vídeo
    const videoSection = document.getElementById('video');
    let videoTracked = false;
    
    window.addEventListener('scroll', function() {
        if (!videoTracked && videoSection && videoSection.getBoundingClientRect().top < window.innerHeight) {
            videoTracked = true;
            if (typeof gtag !== 'undefined') {
                gtag('event', 'video_view', {
                    'event_category': 'engagement',
                    'event_label': 'video_section_viewed'
                });
            }
        }
    });
    
    // Track scroll depth
    let scrollDepths = [25, 50, 75, 100];
    let scrollDepthsReached = [];
    
    window.addEventListener('scroll', function() {
        let scrollPercent = (window.scrollY / (document.documentElement.scrollHeight - window.innerHeight)) * 100;
        
        scrollDepths.forEach(depth => {
            if (scrollPercent >= depth && !scrollDepthsReached.includes(depth)) {
                scrollDepthsReached.push(depth);
                if (typeof gtag !== 'undefined') {
                    gtag('event', 'scroll', {
                        'event_category': 'engagement',
                        'event_label': `scroll_depth_${depth}`
                    });
                }
            }
        });
    });
    
    // Smooth Scroll
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                target.scrollIntoView({ behavior: 'smooth' });
            }
            
            // Close mobile menu if open
            closeMobileMenu();
        });
    });
    
    // Initialize form section
    document.getElementById('noCodeForm').classList.remove('active');
    document.getElementById('hasCodeMessage').classList.remove('active');
    
    // Remove active state from buttons
    document.querySelectorAll('.choice-btn').forEach(btn => {
        btn.classList.remove('active');
    });
    
    // Track page timing
    if (typeof gtag !== 'undefined') {
        window.addEventListener('load', function() {
            const loadTime = performance.timing.loadEventEnd - performance.timing.navigationStart;
            gtag('event', 'timing_complete', {
                'name': 'load',
                'value': loadTime,
                'event_category': 'performance'
            });
        });
    }
});

