/**
 * Calcula quantas vagas devem estar disponíveis baseado no dia e hora
 */
function calcularVagasDisponiveis() {
    const agora = new Date();
    const diaSemana = agora.getDay(); // 0 = Domingo, 1 = Segunda, etc
    const hora = agora.getHours();
    const minutos = agora.getMinutes();
    
    // Configurações
    const VAGAS_INICIAL = 58; // Vagas no início da semana
    const VAGAS_MINIMAS = 5;  // Nunca menos que isso
    const HORA_INICIO = 9;    // Começa a diminuir às 9h
    const HORA_FIM = 20;      // Para de diminuir às 20h
    
    // Calcula qual segunda-feira é o início da semana atual
    const diasDesdeSegunda = diaSemana === 0 ? 6 : diaSemana - 1; // Se domingo, são 6 dias desde segunda
    
    // Calcula quantas horas úteis se passaram desde segunda-feira
    let horasUteisTotais = 0;
    
    // Dias completos anteriores (11 horas úteis por dia: 9h às 20h)
    horasUteisTotais += diasDesdeSegunda * 11;
    
    // Horas do dia atual
    if (hora >= HORA_INICIO && hora < HORA_FIM) {
        horasUteisTotais += (hora - HORA_INICIO);
        // Adiciona fração da hora atual baseado nos minutos
        horasUteisTotais += minutos / 60;
    } else if (hora >= HORA_FIM) {
        // Se já passou das 20h, conta o dia completo
        horasUteisTotais += 11;
    }
    // Se for antes das 9h, não adiciona horas do dia atual
    
    // Diminui aproximadamente 1 vaga por hora útil
    // Com 58 vagas e ~77 horas úteis na semana (7 dias * 11 horas)
    // Isso dá uma redução gradual
    const vagasUsadas = Math.floor(horasUteisTotais * 0.75); // 0.75 para não zerar muito rápido
    
    let vagasAtuais = VAGAS_INICIAL - vagasUsadas;
    
    // Garante que nunca fica abaixo do mínimo
    vagasAtuais = Math.max(VAGAS_MINIMAS, vagasAtuais);
    
    return {
        vagas: vagasAtuais,
        diaSemana: diaSemana,
        diasDesdeSegunda: diasDesdeSegunda,
        horasUteis: horasUteisTotais
    };
}

/**
 * Obtém o número da semana do ano
 */
function getNumeroSemana(data) {
    const primeiroDiaAno = new Date(data.getFullYear(), 0, 1);
    const dias = Math.floor((data - primeiroDiaAno) / (24 * 60 * 60 * 1000));
    return Math.ceil((dias + primeiroDiaAno.getDay() + 1) / 7);
}

/**
 * Calcula quando será a próxima segunda-feira
 */
function getProximaSegunda() {
    const hoje = new Date();
    const diaSemana = hoje.getDay();
    const diasAteSegunda = diaSemana === 0 ? 1 : (8 - diaSemana);
    
    const proximaSegunda = new Date();
    proximaSegunda.setDate(hoje.getDate() + diasAteSegunda);
    proximaSegunda.setHours(0, 0, 0, 0);
    
    return proximaSegunda;
}

/**
 * Sistema principal de gerenciamento de vagas
 */
class SistemaVagas {
    constructor() {
        this.storageKey = 'motorgo_vagas_semanal';
        this.vagas = 58;
        this.semanaAtual = 0;
        this.ultimaAtualizacao = null;
        
        this.init();
    }
    
    init() {
        // Carrega dados salvos ou inicializa novos
        this.carregarDados();
        
        // Atualiza display
        this.atualizarDisplay();
        
        // Atualiza a cada minuto
        setInterval(() => this.atualizarDisplay(), 60000);
        
        // Adiciona listener para mudanças no localStorage (sincronia entre abas)
        window.addEventListener('storage', (e) => {
            if (e.key === this.storageKey) {
                this.carregarDados();
                this.atualizarDisplay();
            }
        });
    }
    
    carregarDados() {
        const agora = new Date();
        const semanaAtual = getNumeroSemana(agora);
        
        // Tenta carregar dados salvos
        const dadosSalvos = localStorage.getItem(this.storageKey);
        
        if (dadosSalvos) {
            const dados = JSON.parse(dadosSalvos);
            
            // Verifica se é a mesma semana
            if (dados.semana === semanaAtual && dados.ano === agora.getFullYear()) {
                // Mesma semana, usa o valor salvo mas recalcula baseado no tempo
                const calculado = calcularVagasDisponiveis();
                this.vagas = calculado.vagas;
                this.semanaAtual = semanaAtual;
            } else {
                // Nova semana, reseta
                this.resetarSemana();
            }
        } else {
            // Primeira vez, inicializa
            this.resetarSemana();
        }
        
        this.ultimaAtualizacao = agora;
    }
    
    resetarSemana() {
        const agora = new Date();
        const calculado = calcularVagasDisponiveis();
        
        this.vagas = calculado.vagas;
        this.semanaAtual = getNumeroSemana(agora);
        
        this.salvarDados();
    }
    
    salvarDados() {
        const dados = {
            vagas: this.vagas,
            semana: this.semanaAtual,
            ano: new Date().getFullYear(),
            ultimaAtualizacao: new Date().toISOString()
        };
        
        localStorage.setItem(this.storageKey, JSON.stringify(dados));
    }
    
    diminuirVaga() {
        // Chamado quando alguém solicita um código
        if (this.vagas > 5) {
            this.vagas--;
            this.salvarDados();
            this.atualizarDisplay();
            
            // Anima a mudança
            const displays = document.querySelectorAll('.spots-count');
            displays.forEach(display => {
                display.style.transform = 'scale(1.2)';
                display.style.color = '#ff0000';
                setTimeout(() => {
                    display.style.transform = 'scale(1)';
                }, 300);
            });
        }
    }
    
    atualizarDisplay() {
        // Recalcula baseado no tempo atual
        const calculado = calcularVagasDisponiveis();
        this.vagas = calculado.vagas;
        
        // Atualiza todos os elementos com a classe spots-count
        const elementos = document.querySelectorAll('.spots-count');
